// Rebuilds prices.data.ts from models.dev, the price list the OpenCode team
// keeps for every provider, OpenCode Go among them:
//
//   bun proxy/src/prices-update.ts
//
// The proxy never fetches it itself. A price decides when shaping rewrites a
// conversation, so a new one arrives as a diff to read and commit, not as a
// change nobody saw on the next start.

import { writeFileSync } from "node:fs";
import { join } from "node:path";

export const SOURCE = "https://models.dev/api.json";

// The providers a route pays (ROUTE_PROVIDERS in prices.ts), and the makers'
// own lists, which price a model reached through a route the table does not
// know.
export const PROVIDERS = ["anthropic", "openai", "google", "opencode-go"];

export type Ratios = readonly [read: number, write: number];
export type Tables = Record<string, Record<string, Ratios>>;

interface Cost {
  input?: unknown;
  cache_read?: unknown;
  cache_write?: unknown;
}
type Api = Record<string, { models?: Record<string, { cost?: Cost }> } | undefined>;

const positive = (value: unknown): value is number => typeof value === "number" && value > 0;
const ratio = (price: number, input: number) => Math.round((price / input) * 10000) / 10000;
// Quoted only where it has to be, as Prettier writes it.
const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `"${name}"`);

// Each model that caches, as its cache read and cache write prices over its
// input price. A model with no write price pays none: the write is billed as
// input. A model with no read price does not cache, so nothing is listed.
export function ratiosFrom(api: unknown): Tables {
  const tables: Tables = {};
  for (const provider of PROVIDERS) {
    const models = (api as Api | undefined)?.[provider]?.models;
    if (!models) throw new Error(`models.dev has no "${provider}"`);
    const table: Record<string, Ratios> = {};
    for (const id of Object.keys(models).sort()) {
      const { input, cache_read: read, cache_write: write } = models[id]?.cost ?? {};
      if (!positive(input) || !positive(read)) continue;
      table[id] = [ratio(read, input), positive(write) ? ratio(write, input) : 1];
    }
    tables[provider] = table;
  }
  return tables;
}

export function dataFile(tables: Tables, day: string): string {
  const lines = [
    `// Generated by \`bun proxy/src/prices-update.ts\` from ${SOURCE} on ${day}.`,
    "// Do not edit: run it again. Each model is [cache read, cache write], over",
    "// its uncached input price.",
    "",
    'import type { Tables } from "./prices-update.ts";',
    "",
    `export const FETCHED = "${day}";`,
    "",
    "export const CACHE_PRICES: Tables = {",
  ];
  for (const [provider, table] of Object.entries(tables)) {
    lines.push(`  ${key(provider)}: {`);
    for (const [id, [read, write]] of Object.entries(table))
      lines.push(`    ${key(id)}: [${read}, ${write}],`);
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

export async function update(
  fetchJson: () => Promise<unknown> = async () => (await fetch(SOURCE)).json(),
  path = join(import.meta.dir, "prices.data.ts"),
  day = new Date().toISOString().slice(0, 10),
): Promise<Tables> {
  const tables = ratiosFrom(await fetchJson());
  writeFileSync(path, dataFile(tables, day));
  return tables;
}

if (import.meta.main) {
  const tables = await update();
  for (const [provider, table] of Object.entries(tables))
    process.stdout.write(`${provider}: ${Object.keys(table).length} models\n`);
}
